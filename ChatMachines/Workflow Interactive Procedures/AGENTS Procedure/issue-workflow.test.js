const assert=require('node:assert/strict');
const {startRun,applyReturn,parseReturn,renderIssue,requestSchema,canonicalTitle}=require('./issue-workflow.js');
const root=__dirname+'/fixtures';
const run=startRun({body:'Test request'});
assert.equal(run.state.render,1);
assert.deepEqual(requestSchema(run),{type:'string'});
assert(!renderIssue(run,7).includes('· Request'));
const before=structuredClone(run);
assert.throws(()=>applyReturn(run,{request:1,values:{'$verbatimUserPrompt':'wrapped'}},root));
assert.deepEqual(run,before);
const send=value=>applyReturn(run,value,root);
send('What does JSON stand for?');
assert.equal(run.state.verbatimUserPrompt,'What does JSON stand for?');
send('Expand JSON.');
assert.deepEqual(requestSchema(run),{type:'boolean'});
send(true);
send({});
send('Expand JSON.');
send({});
assert.equal(run.state.render,7);
send({result:'JavaScript Object Notation'});
assert.equal(run.done,true);
assert.deepEqual(run.state.minimalResult,{result:'JavaScript Object Notation'});
assert.equal(parseReturn('"text"'),'text');
assert.equal(parseReturn('true'),true);
assert.deepEqual(parseReturn('[]'),[]);
assert.equal(canonicalTitle({created_at:'2026-10-15T06:00:00Z'}),'AGENTS Procedure — 2026-10-15T06:00:00.000Z');
console.log('Direct primitive/object returns, wrapper rejection, variable binding, and minimal halt passed.');
